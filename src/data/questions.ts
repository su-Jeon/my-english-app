/**
 * Helper to select 5 random questions for a 5-minute session
 */
export function getRandomSessionQuestions(count = 5): Question[] {
  const shuffled = [...QUESTION_BANK].sort(() => Math.random() - 0.5);
  // Also shuffle the 4 options inside each question so option positions aren't predictable
  return shuffled.slice(0, count).map(q => ({
    ...q,
    options: [...q.options].sort(() => Math.random() - 0.5),
  }));
}
